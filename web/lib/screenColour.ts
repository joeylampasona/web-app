/**
 * The class that colours a screen.
 *
 * Six screens, four colours. Four is the most that stay mutually separable in
 * what the palette has left once gain, loss, the brand and the warn yellow
 * have taken theirs — six crammed into the surviving arc would sit about
 * eighteen degrees apart and read as one family, which is decoration wearing
 * meaning's clothes.
 *
 * So two pairs share, and the pairs are not arbitrary: VCP and the flat base
 * are both contraction bases, blue sky and the IPO base are both a name at its
 * highs with no overhead supply. A reader who notices the repeat learns
 * something true about the shapes rather than being misled by it.
 */
export function screenClass(screen: string): string {
  return `screen--${screen}`;
}
